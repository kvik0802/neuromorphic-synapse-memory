def algebraic_nullstellensatz_certify(n_vars: int, clauses: list, max_rank: int = 16, lr: float = 0.05, steps: int = 400):
    """
    Certifies SAT vs UNSAT using a Burer-Monteiro low-rank factorization 
    of the Sum-of-Squares moment matrix: M = V V^T with V in R^{N x rank}.
    """
    start_time = time.time()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    
    # Low-rank factor V in R^{n_vars x max_rank}
    # Expected boolean moment: X_{ij} = <v_i, v_j>
    # v_0 is the homogenization vector representing the constant '1'
    V = torch.randn(n_vars + 1, max_rank, device=device) * 0.1
    # Fix v_0 to unit norm
    V.data[0] = V.data[0] / torch.norm(V.data[0])
    V = nn.Parameter(V)
    
    optimizer = torch.optim.Adam([V], lr=lr)
    
    c_indices = []
    c_signs = []
    for c in clauses:
        c_indices.append([abs(lit) for lit in c]) # 1-based variable index
        c_signs.append([1 if lit > 0 else -1 for lit in c])
        
    c_idx = torch.tensor(c_indices, dtype=torch.long, device=device)
    c_sgn = torch.tensor(c_signs, dtype=torch.float32, device=device)
    
    certified_status = "UNDETERMINED"
    best_residual = 1e6
    
    for step in range(steps):
        optimizer.zero_grad()
        
        # Gram matrix moments: X_{ij} = v_i . v_j
        # Variable relaxation: x_i in [0, 1] is mapped from inner product <v_i, v_0>
        # x_i = (1 + <v_i, v_0>) / 2 in [0, 1]
        v0 = V[0:1] # [1, rank]
        vi = V[1:]  # [n_vars, rank]
        
        # Unit norm penalty on vectors: ||v_i||^2 == 1 (forces boolean relaxation)
        norm_penalty = torch.mean((torch.sum(V ** 2, dim=-1) - 1.0) ** 2)
        
        # Inner products with v0
        inner_v0 = torch.matmul(vi, v0.t()).squeeze(-1) # [n_vars] in [-1, 1]
        x_prob = (1.0 + inner_v0) / 2.0 # [n_vars] in [0, 1]
        
        # Clause polynomials: q_c = Prod_{l in c} (1 - x_l)
        # If lit is positive: false when x=0 -> (1 - x)
        # If lit is negative: false when x=1 -> x
        c_vars = x_prob[c_idx - 1] # [n_clauses, 3]
        # Literal false factors:
        false_factors = torch.where(c_sgn > 0, 1.0 - c_vars, c_vars)
        clause_violation = torch.prod(false_factors, dim=-1) # [n_clauses]
        
        # Nullstellensatz Infeasibility Energy:
        # Sum of squared clause polynomials + boolean constraints
        ideal_loss = torch.sum(clause_violation ** 2) + 2.0 * norm_penalty
        
        ideal_loss.backward()
        optimizer.step()
        
        with torch.no_grad():
            res = ideal_loss.item()
            if res < best_residual:
                best_residual = res
                
            # Check discrete projection for SAT certificate
            disc_x = (inner_v0 > 0.0).float()
            c_disc = disc_x[c_idx - 1]
            disc_false = torch.where(c_sgn > 0, 1.0 - c_disc, c_disc)
            unsat_count = torch.sum(torch.prod(disc_false, dim=-1) > 0.5).item()
            
            if unsat_count == 0:
                certified_status = "CERTIFIED_SAT"
                break
                
    elapsed = time.time() - start_time
    if certified_status == "UNDETERMINED":
        # If residual is bounded strictly away from zero under rank exhaustion:
        if best_residual > 0.1:
            certified_status = "PROBABLE_UNSAT_IN_IDEAL"
            
    return certified_status, best_residual, elapsed


